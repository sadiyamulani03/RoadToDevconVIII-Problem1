#!/usr/bin/env node
// Copies deployments/<chainId>.json (written by the Foundry deploy script)
// into the frontend config so builds carry the real deployed address.
// Usage: node scripts/sync-deployment.mjs [chainId]
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const chainId = process.argv[2] ?? '84532'
const deploymentPath = join(here, '..', 'deployments', `${chainId}.json`)
const outPath = join(here, 'frontend', 'src', 'config', 'deployment.generated.ts')

if (!existsSync(deploymentPath)) {
  console.error(`No deployment metadata at ${deploymentPath}. Deploy first.`)
  process.exit(1)
}

const d = JSON.parse(readFileSync(deploymentPath, 'utf8'))
if (!/^0x[0-9a-fA-F]{40}$/.test(d.address ?? '')) {
  console.error(`Deployment file has no valid address: ${deploymentPath}`)
  process.exit(1)
}

const block = d.deployBlock ?? d.deployedAtBlock ?? 0
const out = `// AUTO-GENERATED by scripts/sync-deployment.mjs — do not edit by hand.
// Source: deployments/${chainId}.json
export const GENERATED_ADDRESS = '${d.address}'
export const GENERATED_DEPLOY_BLOCK = ${block}n
`
writeFileSync(outPath, out)
console.log(`wrote ${outPath}`)
console.log(`  address:    ${d.address}`)
console.log(`  chainId:    ${d.chainId ?? chainId}`)
console.log(`  deployBlock: ${block}${block === 0 ? ' (set deployBlock in deployments/' + chainId + '.json to enable the recent-games index)' : ''}`)
