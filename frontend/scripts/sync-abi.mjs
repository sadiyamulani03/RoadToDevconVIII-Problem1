#!/usr/bin/env node
// Regenerates frontend/src/config/ConnectFour.abi.ts from the compiled
// Foundry artifact. Run after changing src/ConnectFour.sol:
//   (cd .. && forge build) && node scripts/sync-abi.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const artifactPath = join(here, '..', '..', 'out', 'ConnectFour.sol', 'ConnectFour.json')
const outPath = join(here, '..', 'src', 'config', 'ConnectFour.abi.ts')

const artifact = JSON.parse(readFileSync(artifactPath, 'utf8'))
if (!artifact.abi) throw new Error('artifact has no abi field')
mkdirSync(dirname(outPath), { recursive: true })
const header = `// AUTO-GENERATED by frontend/scripts/sync-abi.mjs — do not edit by hand.\n// Source of truth: src/ConnectFour.sol (forge artifact out/ConnectFour.sol).\n`
writeFileSync(outPath, header + 'export const connectFourAbi = ' + JSON.stringify(artifact.abi, null, 2) + ' as const\n')
console.log(`wrote ${outPath} (${artifact.abi.length} entries)`)
